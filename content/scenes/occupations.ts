// - Lille textile decline in the 1960s, the Creusot-Loire bankruptcy in 1984, Corby steelworks closure decided
//   in 1979, the collapse of Łódź textiles after 1990: events and contexts of the respective world packs.
// Workplaces are named only where those records place them; elsewhere the workplace is generic.
// `from`/`to` bound the year she could START the job there; lines are first person, original fiction.

